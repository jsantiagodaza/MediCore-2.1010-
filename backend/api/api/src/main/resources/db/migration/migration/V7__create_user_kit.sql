create table user_kit_item (
    id          bigint generated by default as identity primary key,
    user_id     bigint       not null,
    medicine_id bigint       not null,
    quantity    int          not null default 1,
    notes       varchar(300),
    created_at  timestamp    not null,
    updated_at  timestamp    not null,
    constraint fk_kit_user
        foreign key (user_id) references users (id) on delete cascade,
    constraint fk_kit_medicine
        foreign key (medicine_id) references medicine (id),
    constraint uq_kit_user_medicine unique (user_id, medicine_id),
    constraint ck_kit_quantity check (quantity between 1 and 99)
);

create index idx_kit_user on user_kit_item (user_id);
create index idx_kit_medicine on user_kit_item (medicine_id);