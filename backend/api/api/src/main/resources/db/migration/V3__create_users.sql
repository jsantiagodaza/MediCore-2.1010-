-- ============================================================
--  V3: usuarios y sesiones
--
--  Las contrasenas se guardan SIEMPRE como hash BCrypt (60 chars),
--  nunca en texto plano. Los tokens de sesion se guardan hasheados
--  (SHA-256): si alguien lee la base, no puede reutilizarlos.
-- ============================================================

create table users (
    id            bigint generated by default as identity primary key,
    email         varchar(255) not null,
    name          varchar(120),
    password_hash varchar(100) not null,
    created_at    timestamp not null,
    constraint uq_users_email unique (email)
);

create table user_session (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null,
    token_hash varchar(64) not null,
    created_at timestamp not null,
    expires_at timestamp not null,
    revoked    boolean not null default false,
    constraint fk_user_session_user foreign key (user_id) references users (id),
    constraint uq_user_session_token unique (token_hash)
);

create index idx_user_session_user on user_session (user_id);
