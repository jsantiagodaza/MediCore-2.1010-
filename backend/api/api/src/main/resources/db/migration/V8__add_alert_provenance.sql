alter table season_alert add column origin varchar(80);
alter table season_alert add column external_id varchar(160);
alter table season_alert add column fetched_at timestamp;

create unique index uq_alert_origin_external
    on season_alert (origin, external_id);

create table alert_source_run (
    id             bigint generated by default as identity primary key,
    source_id      varchar(80)  not null,
    status         varchar(20)  not null,
    alerts_imported int         not null default 0,
    error_message  varchar(500),
    started_at     timestamp    not null,
    finished_at    timestamp,
    constraint ck_source_run_status
        check (status in ('OK', 'ERROR'))
);

create index idx_source_run_source on alert_source_run (source_id);
create index idx_source_run_started on alert_source_run (started_at);