-- ============================================================
--  V4: alertas por temporada y preferencias de alertas
--  Portable: funciona igual en H2 (dev) y PostgreSQL (prod).
-- ============================================================

create table season_alert (
    id          bigint generated by default as identity primary key,
    title       varchar(160)  not null,
    description varchar(2000) not null,
    category    varchar(80)   not null,
    risk_level  varchar(20)   not null,
    city        varchar(120),
    region      varchar(120)  not null,
    source      varchar(160),
    starts_on   date          not null,
    ends_on     date,
    active      boolean       not null default true,
    created_at  timestamp     not null,
    constraint ck_season_alert_risk
        check (risk_level in ('BAJO', 'MEDIO', 'ALTO', 'CRITICO'))
);

create index idx_season_alert_city on season_alert (city);
create index idx_season_alert_region on season_alert (region);
create index idx_season_alert_category on season_alert (category);
create index idx_season_alert_risk on season_alert (risk_level);
create index idx_season_alert_active on season_alert (active);

create table alert_preference (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null,
    city       varchar(120),
    region     varchar(120),
    category   varchar(80),
    risk_level varchar(20) not null,
    enabled    boolean     not null default true,
    created_at timestamp   not null,
    updated_at timestamp   not null,
    constraint fk_alert_preference_user
        foreign key (user_id) references users (id),
    constraint uq_alert_preference_user unique (user_id),
    constraint ck_alert_preference_risk
        check (risk_level in ('BAJO', 'MEDIO', 'ALTO', 'CRITICO'))
);

create index idx_alert_preference_user on alert_preference (user_id);