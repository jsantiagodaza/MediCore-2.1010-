-- ============================================================
--  V6: registro de envios de notificaciones por correo
-- ============================================================

create table notification_delivery (
    id            bigint generated by default as identity primary key,
    user_id       bigint       not null,
    alert_id      bigint       not null,
    recipient     varchar(255) not null,
    status        varchar(20)  not null,
    attempts      int          not null default 0,
    error_message varchar(500),
    sent_at       timestamp,
    created_at    timestamp    not null,
    constraint fk_delivery_user
        foreign key (user_id) references users (id),
    constraint fk_delivery_alert
        foreign key (alert_id) references season_alert (id),
    constraint uq_delivery_user_alert unique (user_id, alert_id),
    constraint ck_delivery_status
        check (status in ('ENVIADO', 'FALLIDO', 'OMITIDO'))
);

create index idx_delivery_user on notification_delivery (user_id);
create index idx_delivery_alert on notification_delivery (alert_id);
create index idx_delivery_status on notification_delivery (status);