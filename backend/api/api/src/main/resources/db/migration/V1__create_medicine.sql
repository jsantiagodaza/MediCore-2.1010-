-- ============================================================
--  V1: esquema del catalogo de medicamentos
--  Portable: funciona igual en H2 (dev) y PostgreSQL (prod).
-- ============================================================

create table medicine (
    id             bigint generated by default as identity primary key,
    name           varchar(200) not null,
    category       varchar(120),
    category_class varchar(40),
    dose           varchar(120),
    uses           varchar(2000),
    posology       varchar(2000),
    when_to_take   varchar(2000),
    mol_tip        varchar(2000),
    emoji          varchar(16)
);

create table medicine_precaution (
    medicine_id bigint not null,
    precaution  varchar(500) not null,
    constraint fk_medicine_precaution_medicine
        foreign key (medicine_id) references medicine (id)
);

create index idx_medicine_name on medicine (name);
create index idx_medicine_category on medicine (category);
create index idx_medicine_precaution_medicine on medicine_precaution (medicine_id);
